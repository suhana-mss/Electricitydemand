"""Streamlit dashboard: forecast + XAI + GenAI recommendations.  Run: streamlit run app.py"""
import json
import pickle

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from src.data import inverse_target, make_windows, TARGET
from src.explain import shap_explain, feature_ablation, build_dag, draw_dag
from src.recommend import build_context, generate

st.set_page_config(page_title="GenAI Electricity Demand Forecasting", page_icon="⚡", layout="wide")

with open("styles.css") as _f:
    st.markdown(f"<style>{_f.read()}</style>", unsafe_allow_html=True)

DARK = dict(template="plotly_dark", paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)",
            font=dict(family="Inter, sans-serif"), colorway=["#22d3ee", "#ffb703", "#34d399"])

st.title("⚡ GenAI-Enhanced Electricity Demand Forecasting")


@st.cache_resource
def load_artifacts():
    from tensorflow import keras
    model = keras.models.load_model("artifacts/lstm.keras")
    prep = pickle.load(open("artifacts/prep.pkl", "rb"))
    feats = pd.read_pickle("artifacts/feats.pkl")
    metrics = json.load(open("artifacts/metrics.json"))
    return model, prep, feats, metrics


try:
    model, prep, feats, metrics = load_artifacts()
except Exception:
    st.error("No trained model found. Run `python train.py` first.")
    st.stop()

scaler, cols, t, lb = prep["scaler"], prep["cols"], prep["target_idx"], prep["lookback"]
arr = scaler.transform(feats.values)
X, y = make_windows(arr, t, lb)
ts = feats.index[lb:]
test_start = prep["s2"]

with st.sidebar:
    st.header("Settings")
    st.caption(f"Data source: {prep['source']}")
    n_test = len(X) - test_start
    pos = st.slider("Select forecast point (test period)", 0, n_test - 1, n_test // 2)
    use_llm = st.checkbox("Use LLM for recommendations (needs ANTHROPIC_API_KEY)", value=True)
    st.subheader("Model test metrics")
    for k, v in metrics.items():
        st.metric(k, f"{v:.3f}")

i = test_start + pos
x = X[i]
pred = float(inverse_target(scaler, t, model.predict(x[None], verbose=0).ravel())[0])
actual = float(inverse_target(scaler, t, np.array([y[i]]))[0])

# --- Forecast ---
st.subheader("1. Demand forecast")
lo = max(test_start, i - 72)
seg = range(lo, i + 1)
hist = inverse_target(scaler, t, y[lo:i + 1])
fig = go.Figure()
fig.add_trace(go.Scatter(x=ts[lo:i + 1], y=hist, name="Actual", mode="lines"))
fig.add_trace(go.Scatter(x=[ts[i]], y=[pred], name="Forecast", mode="markers", marker=dict(size=12, color="red")))
fig.update_layout(height=320, yaxis_title="kW", margin=dict(t=10), **DARK)
st.plotly_chart(fig, use_container_width=True)
c1, c2 = st.columns(2)
c1.metric("Forecast (kW)", f"{pred:.3f}")
c2.metric("Actual (kW)", f"{actual:.3f}", delta=f"{pred - actual:+.3f} error", delta_color="off")

# --- XAI ---
st.subheader("2. Why this forecast? (Explainable AI)")
bg = X[max(0, test_start - 200):test_start]
with st.spinner("Computing SHAP and feature ablation..."):
    sv = shap_explain(model, x, bg, cols)
    ab = feature_ablation(model, x, bg, cols)
sv_kw = {k: v * (scaler.data_max_[t] - scaler.data_min_[t]) for k, v in sv.items()}
ab_kw = {k: v * (scaler.data_max_[t] - scaler.data_min_[t]) for k, v in ab.items()}
df_x = pd.DataFrame({"SHAP (kW)": sv_kw, "Ablation Δ (kW)": ab_kw}).sort_values("SHAP (kW)", key=abs)
fx = go.Figure()
fx.add_trace(go.Bar(y=df_x.index, x=df_x["SHAP (kW)"], orientation="h", name="SHAP"))
fx.add_trace(go.Bar(y=df_x.index, x=df_x["Ablation Δ (kW)"], orientation="h", name="Feature ablation"))
fx.update_layout(barmode="group", height=420, margin=dict(t=10), xaxis_title="Effect on forecast (kW)", **DARK)
st.plotly_chart(fx, use_container_width=True)
with st.expander("Variable relationship DAG (assumed structure, not proven causality)"):
    st.pyplot(draw_dag(build_dag(cols)))

# --- Recommendations ---
st.subheader("3. Energy-management recommendations")
recent_avg = float(np.mean(hist[-24:])) if len(hist) >= 24 else float(np.mean(hist))
day = feats.loc[ts[i] - pd.Timedelta(hours=24):ts[i], TARGET]
peak_hour = int(day.idxmax().hour)
ctx = build_context(pred, recent_avg, peak_hour, sv_kw, ab_kw)
recs, mode = generate(ctx, use_llm=use_llm)
for r in recs:
    st.markdown(f"- {r}")
st.caption(f"Generated by: {mode}. Grounded only in the forecast/XAI facts below.")
with st.expander("Facts passed to the recommender"):
    st.json(ctx)

# --- Feedback ---
st.subheader("4. Feedback")
rating = st.slider("Rate these recommendations", 1, 5, 4)
if st.button("Submit feedback"):
    with open("artifacts/feedback.jsonl", "a") as f:
        f.write(json.dumps({"ts": str(ts[i]), "rating": rating, "mode": mode}) + "\n")
    st.success("Thanks, feedback saved for model improvement.")